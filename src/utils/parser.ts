/**
 * Checks duplicate status of a list of students
 */
export function analyzeDuplicates(students: Student[]) {
  const nameCounts = new Map<string, number>();
  students.forEach((s) => {
    const clean = s.name.trim();
    nameCounts.set(clean, (nameCounts.get(clean) || 0) + 1);
  });

  const duplicateNames = new Set<string>();
  nameCounts.forEach((count, name) => {
    if (count > 1) {
      duplicateNames.add(name);
    }
  });

  let duplicateTotalEntries = 0;
  nameCounts.forEach((count) => {
    if (count > 1) {
      duplicateTotalEntries += (count - 1);
    }
  });

  return {
    duplicateNames,
    duplicateGroupsCount: duplicateNames.size,
    duplicateTotalEntries,
  };
}

/**
 * Removes duplicate students by name, preserving only the first occurrence
 */
export function removeDuplicateStudents(students: Student[]): Student[] {
  const seen = new Set<string>();
  const result: Student[] = [];

  students.forEach((s) => {
    const clean = s.name.trim();
    if (!seen.has(clean)) {
      seen.add(clean);
      result.push(s);
    }
  });

  return result;
}

/**
 * Parses raw text or CSV content
 * Supports:
 * - "學號,姓名" or "座號,姓名" (e.g. D1387525,蘇盷蓉 or 01,王小明)
 * - "01 王小明" or "1. 李美美" or "1\t王小明" or "D1387525 蘇盷蓉"
 * - Comma / Tab separated single line
 * - One name per line
 */
export function parsePastedText(text: string): Student[] {
  if (!text || !text.trim()) return [];

  // Remove potential BOM and normalize newlines
  const cleanText = text.replace(/^\uFEFF/, '').trim();
  const rawLines = cleanText.split(/\r?\n/).map(l => l.trim()).filter(Boolean);
  if (rawLines.length === 0) return [];

  const students: Student[] = [];

  // Check if single line separated by commas or tabs or spaces
  if (rawLines.length === 1 && (rawLines[0].includes(',') || rawLines[0].includes('、') || rawLines[0].includes('\t'))) {
    const rawItems = rawLines[0].split(/[,、\t]+/).map(s => s.trim()).filter(Boolean);
    return rawItems.map((item, index) => ({
      id: `std-${Date.now()}-${index}-${Math.random().toString(36).substr(2, 4)}`,
      name: item,
      seatNumber: String(index + 1).padStart(2, '0')
    }));
  }

  // Detect header row index
  let headerColSeat = -1;
  let headerColName = -1;

  let startIndex = 0;
  const firstLine = rawLines[0];
  const firstLineCols = firstLine.split(/[,;\t]/).map(c => c.trim().toLowerCase());

  const seatKeywords = ['學號', '座號', '編號', 'id', 'no', 'number', 'seat', 'code'];
  const nameKeywords = ['姓名', '學生姓名', '名字', 'name', 'student'];

  const hasSeatHeader = firstLineCols.some(col => seatKeywords.some(kw => col.includes(kw)));
  const hasNameHeader = firstLineCols.some(col => nameKeywords.some(kw => col.includes(kw)));

  if (hasSeatHeader || hasNameHeader) {
    startIndex = 1;
    firstLineCols.forEach((col, idx) => {
      if (seatKeywords.some(kw => col.includes(kw))) headerColSeat = idx;
      if (nameKeywords.some(kw => col.includes(kw))) headerColName = idx;
    });
  }

  for (let i = startIndex; i < rawLines.length; i++) {
    const line = rawLines[i].trim();
    if (!line) continue;

    // Pattern A: CSV with commas/semicolons/tabs
    const csvParts = line.split(/[,;\t]/).map(p => p.trim().replace(/^["']|["']$/g, ''));
    if (csvParts.length >= 2) {
      let seatVal = '';
      let nameVal = '';

      if (headerColSeat !== -1 && headerColName !== -1 && csvParts[headerColSeat] && csvParts[headerColName]) {
        seatVal = csvParts[headerColSeat];
        nameVal = csvParts[headerColName];
      } else {
        // Infer: if one part looks like ID/number (digits or starts with letter+digits like D1420473)
        const isPart0IdLike = /^([A-Za-z0-9_\-#]+)$/.test(csvParts[0]) && csvParts[0].length <= 15;
        const isPart1IdLike = /^([A-Za-z0-9_\-#]+)$/.test(csvParts[1]) && csvParts[1].length <= 15;

        if (isPart0IdLike && !isPart1IdLike) {
          seatVal = csvParts[0];
          nameVal = csvParts[1];
        } else if (isPart1IdLike && !isPart0IdLike) {
          seatVal = csvParts[1];
          nameVal = csvParts[0];
        } else {
          // Default: col 0 is seat, col 1 is name
          seatVal = csvParts[0];
          nameVal = csvParts[1];
        }
      }

      if (nameVal) {
        students.push({
          id: `std-${Date.now()}-${i}-${Math.random().toString(36).substr(2, 4)}`,
          seatNumber: seatVal,
          name: nameVal
        });
        continue;
      }
    }

    // Pattern B: "01 王小明" or "D1420473 王小明" or "1. 王小明"
    const matchWithCode = line.match(/^([A-Za-z0-9_\-]+)[\s.,、\-]+(.+)$/);
    if (matchWithCode) {
      const code = matchWithCode[1].trim();
      const name = matchWithCode[2].trim().replace(/^["']|["']$/g, '');
      if (name) {
        students.push({
          id: `std-${Date.now()}-${i}-${Math.random().toString(36).substr(2, 4)}`,
          seatNumber: code,
          name
        });
        continue;
      }
    }

    // Pattern C: Single line name
    const cleanName = line.replace(/^["']|["']$/g, '').trim();
    if (cleanName) {
      students.push({
        id: `std-${Date.now()}-${i}-${Math.random().toString(36).substr(2, 4)}`,
        seatNumber: String(students.length + 1).padStart(2, '0'),
        name: cleanName
      });
    }
  }

  return students;
}

/**
 * Parses uploaded CSV file content
 */
export function parseCSVContent(content: string): Student[] {
  return parsePastedText(content);
}

/**
 * Exports roster to CSV formatted string
 */
export function exportRosterToCSV(students: Student[]): string {
  const header = '學號/座號,姓名\n';
  const rows = students.map(s => `${s.seatNumber || ''},${s.name}`).join('\n');
  return '\uFEFF' + header + rows;
}
